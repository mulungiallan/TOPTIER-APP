const dictionaries: Record<string, Dict> = { en, es, fr, sw, ar, zh }

// ─── Public API ─────────────────────────────────────────────────────────────

export function detectUserLocale(): string {
  if (typeof navigator === 'undefined') return defaultLocale
  const browserLang = navigator.language.split('-')[0].toLowerCase()
  if (locales[browserLang]) return browserLang
  return defaultLocale
}

export function t(key: string, locale: string = defaultLocale): string {
  const dict = dictionaries[locale] || dictionaries[defaultLocale]
  return dict[key] || dictionaries[defaultLocale][key] || key
}

export function isRTL(locale: string): boolean {
  return locales[locale]?.direction === 'rtl'
}

export function getLocaleCurrency(locale: string): string {
  return locales[locale]?.currency || 'USD'
}
